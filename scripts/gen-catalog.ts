/**
 * Merges `docs-desktop/sites.d/<id>.json` (atomic per-site sources) into
 * `docs-desktop/sites.json` — the single catalog artifact consumed by:
 *
 *   - docs-desktop/src/brands.ts        (frontend catalog adapter)
 *   - docs-desktop/src-tauri/src/catalog.rs   (origin/entry resolution)
 *   - scripts/ci-build-site.ts          (crawl/pack config)
 *
 * Usage:
 *   bun scripts/gen-catalog.ts           # merge + validate
 *   bun scripts/gen-catalog.ts --check   # CI mode: fail if sites.json is stale
 */
import fs from "fs";
import path from "path";

const root = path.resolve(import.meta.dir, "..");
const sitesDir = path.join(root, "docs-desktop", "sites.d");
const outPath = path.join(root, "docs-desktop", "sites.json");

interface CatalogSite {
  id: string;
  order: number;
  name: string;
  version: string;
  category: string;
  color: string;
  bgTint: string;
  description: string;
  origin?: string;
  entryPath: string;
  allowedPrefixes?: string[];
  maxPages?: number;
  defaultRoutes?: { label: string; path: string }[];
  svg: string;
}

const meta = JSON.parse(fs.readFileSync(path.join(sitesDir, "_catalog.json"), "utf8"));
const categories: string[] = meta.categories;

const errors: string[] = [];
const warnings: string[] = [];
const seen = new Set<string>();
const sites: CatalogSite[] = [];

const files = fs
  .readdirSync(sitesDir)
  .filter((f) => f.endsWith(".json") && f !== "_catalog.json")
  .sort();

for (const file of files) {
  const s = JSON.parse(fs.readFileSync(path.join(sitesDir, file), "utf8")) as CatalogSite;

  if (s.id !== file.replace(/\.json$/, "")) errors.push(`${file}: "id" must match filename`);
  if (seen.has(s.id)) errors.push(`duplicate site id: ${s.id}`);
  seen.add(s.id);

  const required = ["name", "version", "category", "color", "bgTint", "description", "entryPath", "svg"] as const;
  for (const f of required) if (!s[f]) errors.push(`${file}: missing field "${f}"`);

  if (!categories.includes(s.category)) {
    errors.push(`${file}: unknown category "${s.category}" (add it to _catalog.json)`);
  }

  const embedded = (s as unknown as { kind?: string }).kind === "embedded";
  if (!embedded) {
    if (!s.origin) errors.push(`${file}: non-embedded site requires "origin"`);
    if (!s.allowedPrefixes?.length) errors.push(`${file}: crawlable site requires "allowedPrefixes"`);
  }

  if (typeof s.order !== "number" || s.order < 0) errors.push(`${file}: missing numeric "order"`);
  if (!s.svg.startsWith("<svg")) errors.push(`${file}: "svg" must be an inline <svg> string`);

  sites.push(s);
}

if (sites.length === 0) errors.push("no site files found");
const embeddedCount = sites.filter((s) => (s as unknown as { kind?: string }).kind === "embedded").length;
console.log(
  `sites: ${sites.length} (${embeddedCount} embedded, ${sites.length - embeddedCount} crawlable) in ${categories.length} categories`,
);

if (errors.length) {
  console.error("Validation failed:");
  for (const e of errors) console.error("  ✗ " + e);
  process.exit(1);
}
for (const w of warnings) console.warn("  ⚠ " + w);

// category-major, then explicit order field, then id for determinism
sites.sort(
  (a, b) =>
    categories.indexOf(a.category) - categories.indexOf(b.category) ||
    a.order - b.order ||
    a.id.localeCompare(b.id),
);

const out = {
  $meta: {
    source: "generated from sites.d/*.json by scripts/gen-catalog.ts — DO NOT EDIT THIS FILE DIRECTLY",
    generatedAt: new Date().toISOString(),
    siteCount: sites.length,
  },
  categories,
  sites,
};

const args = process.argv.slice(2);
if (args.includes("--check")) {
  // CI mode: verify sites.json is up to date relative to sites.d without writing.
  const onDisk = fs.readFileSync(outPath, "utf8");
  const diskSites = JSON.stringify(JSON.parse(onDisk).sites);
  const merged = sites; // validated above
  if (diskSites !== JSON.stringify(merged)) {
    console.error("sites.json is stale → run `bun scripts/gen-catalog.ts` and commit.");
    process.exit(1);
  }
  console.log("sites.json is up to date.");
  process.exit(0);
}

const prevText = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
const nextText = JSON.stringify(out, null, 2) + "\n";
// generatedAt would diff on every run — keep stable between content-only changes
if (prevText) {
  try {
    const prev = JSON.parse(prevText);
    const prevSites = JSON.stringify(prev.sites);
    const nextSites = JSON.stringify(out.sites);
    if (prevSites === nextSites) {
      console.log("sites.json unchanged (content-identical), keeping previous timestamp");
      process.exit(0);
    }
  } catch {
    /* fallthrough and rewrite */
  }
}

fs.writeFileSync(outPath, nextText);
console.log(`Wrote docs-desktop/sites.json (${sites.length} sites)`);
